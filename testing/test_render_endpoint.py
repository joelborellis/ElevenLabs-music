def test_render_validation():
    """Test the /render endpoint with invalid input.

    Covers the mutual-exclusivity contract between 'prompt' and 'chunks':
    - empty chunks + no prompt  -> 422
    - both prompt and chunks    -> 422
    - music_length_ms w/o prompt -> 422
    """

    url = f"{BASE_URL}/render"

    cases = [
        {
            "name": "empty chunks + no prompt",
            "payload": {"chunks": []},
        },
        {
            "name": "both prompt and chunks (mutually exclusive)",
            "payload": {
                "prompt": "an upbeat track",
                "chunks": [
                    {
                        "text": "[Intro]",
                        "positive_styles": ["120 bpm"],
                        "negative_styles": [],
                        "duration_ms": 4000,
                        "context_adherence": "high",
                    }
                ],
            },
        },
        {
            "name": "music_length_ms without prompt",
            "payload": {
                "music_length_ms": 30000,
                "chunks": [
                    {
                        "text": "[Intro]",
                        "positive_styles": ["120 bpm"],
                        "negative_styles": [],
                        "duration_ms": 4000,
                        "context_adherence": "high",
                    }
                ],
            },
        },
    ]

    all_passed = True
    for case in cases:
        print(f"\nTesting validation - {case['name']} (should return 422)")
        print("-" * 50)
        try:
            response = requests.post(url, json=case["payload"], timeout=60)
            print(f"Status: {response.status_code}")
            if response.status_code == 422:
                print(f"✅ Correctly returned 422 for: {case['name']}")
            else:
                print(f"❌ Expected 422, got {response.status_code}")
                print(f"Response: {response.text[:500]}")
                all_passed = False
        except Exception as e:
            print(f"❌ Error: {e}")
            all_passed = False

    return all_passed


def run_all_tests():
    """Run all render endpoint tests."""

    print("=" * 60)
    print("RENDER ENDPOINT TESTS")
    print("=" * 60)

    # Test 404 handling first (quick test)
    test_download_not_found()

    # Test render with title (custom filename)
    test_render_endpoint_with_title()

    # Test prompt-mode render with extra pass-through params
    test_render_prompt_mode()

    # Test the main render endpoint (composition-plan mode)
    result = test_render_endpoint()

    if result:
        filename = result.get("filename")

        if filename:
            # Test download endpoint
            test_download_endpoint(filename)

            # Test stream endpoint
            test_stream_endpoint(filename)

    # Test validation (mutual-exclusivity rules)
    test_render_validation()
    
    print("\n" + "=" * 60)
    print("TESTS COMPLETE")
    print("=" * 60)


if __name__ == "__main__":
    run_all_tests()
