"""
Test script for the /render endpoint.
"""

import requests
import json
import os
from pathlib import Path

BASE_URL = "http://localhost:8000"

# Render request payloads live in this JSON file so variations can be changed
# without editing the script. Keys: "plan_mode", "with_title", "prompt_mode".
RENDER_INPUT_PATH = Path(__file__).parent / "render_test_input.json"

# Optional: the render-ready plan produced by test_plan_endpoint.py. When present,
# the plan-mode render uses this exact plan instead of the static "plan_mode"
# fallback in render_test_input.json.
GENERATED_PLAN_PATH = Path(__file__).parent / "generated_comp_plan.json"


def load_render_inputs() -> dict:
    """Load the render request payloads from the JSON file."""
    with open(RENDER_INPUT_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def load_plan_payload() -> dict:
    """Return the plan-mode payload, preferring the plan endpoint's output.

    If generated_comp_plan.json exists (written by test_plan_endpoint.py), that
    exact plan is rendered; otherwise the static "plan_mode" entry from
    render_test_input.json is used.
    """
    if GENERATED_PLAN_PATH.exists():
        print(f"Using generated plan from: {GENERATED_PLAN_PATH.name}")
        with open(GENERATED_PLAN_PATH, "r", encoding="utf-8") as f:
            return json.load(f)
    print(f"No {GENERATED_PLAN_PATH.name} found — using 'plan_mode' from {RENDER_INPUT_PATH.name}")
    return load_render_inputs()["plan_mode"]


def test_render_endpoint():
    """Test the /render endpoint with a composition plan (plan-mode)."""

    url = f"{BASE_URL}/render"

    # Prefer the plan generated by test_plan_endpoint.py, else the static payload
    payload = load_plan_payload()

    print(f"Testing POST {url}")
    print(f"Composition plan chunks: {len(payload.get('chunks', []))}")
    print("-" * 50)

    try:
        response = requests.post(url, json=payload, timeout=300)
        response.raise_for_status()
        
        result = response.json()
        print(f"Status: {response.status_code}")
        print("\n" + "=" * 60)
        print("FULL RESPONSE DETAILS")
        print("=" * 60)
        
        # Print each top-level key and its value
        for key, value in result.items():
            print(f"\n--- {key} ---")
            if isinstance(value, dict):
                print(json.dumps(value, indent=2))
            elif isinstance(value, list):
                print(json.dumps(value, indent=2))
            else:
                print(value)
        
        print("\n" + "=" * 60)
        print("RAW JSON RESPONSE")
        print("=" * 60)
        print(json.dumps(result, indent=2))
        
        # Validate response structure
        assert "filename" in result, "Response missing 'filename'"
        assert "file_path" in result, "Response missing 'file_path'"
        assert "download_url" in result, "Response missing 'download_url'"
        assert "file_size_bytes" in result, "Response missing 'file_size_bytes'"
        assert "request_id" in result, "Response missing 'request_id'"
        
        print("\n✅ Render test passed!")
        return result
        
    except requests.exceptions.ConnectionError:
        print("❌ Error: Could not connect to server. Is it running?")
        return None
    except requests.exceptions.Timeout:
        print("❌ Error: Request timed out. Rendering may take a while.")
        return None
    except requests.exceptions.HTTPError as e:
        print(f"❌ HTTP Error: {e}")
        print(f"Response: {response.text}")
        return None
    except Exception as e:
        print(f"❌ Error: {e}")
        return None


def test_download_endpoint(filename: str):
    """Test the /render/download/{filename} endpoint."""
    
    url = f"{BASE_URL}/render/download/{filename}"
    
    print(f"\nTesting GET {url}")
    print("-" * 50)
    
    try:
        response = requests.get(url, stream=True, timeout=60)
        response.raise_for_status()
        
        # Check content type
        content_type = response.headers.get("Content-Type", "")
        print(f"Content-Type: {content_type}")
        
        # Save to local file for verification
        output_dir = os.path.join(os.path.dirname(__file__), "music")
        os.makedirs(output_dir, exist_ok=True)
        output_path = os.path.join(output_dir, f"downloaded_{filename}")
        
        with open(output_path, "wb") as f:
            for chunk in response.iter_content(chunk_size=8192):
                f.write(chunk)
        
        file_size = os.path.getsize(output_path)
        print(f"Downloaded file size: {file_size} bytes")
        print(f"Saved to: {output_path}")
        
        assert file_size > 0, "Downloaded file is empty"
        assert "audio" in content_type or "mpeg" in content_type, f"Unexpected content type: {content_type}"
        
        print("\n✅ Download test passed!")
        return output_path
        
    except requests.exceptions.HTTPError as e:
        print(f"❌ HTTP Error: {e}")
        print(f"Response: {response.text}")
        return None
    except Exception as e:
        print(f"❌ Error: {e}")
        return None


def test_stream_endpoint(filename: str):
    """Test the /render/stream/{filename} endpoint."""
    
    url = f"{BASE_URL}/render/stream/{filename}"
    
    print(f"\nTesting GET {url}")
    print("-" * 50)
    
    try:
        response = requests.get(url, stream=True, timeout=60)
        response.raise_for_status()
        
        # Check headers
        content_type = response.headers.get("Content-Type", "")
        content_length = response.headers.get("Content-Length", "unknown")
        
        print(f"Content-Type: {content_type}")
        print(f"Content-Length: {content_length}")
        
        # Read first chunk to verify streaming works
        first_chunk = next(response.iter_content(chunk_size=8192))
        print(f"First chunk size: {len(first_chunk)} bytes")
        
        assert len(first_chunk) > 0, "Stream returned empty data"
        assert "audio" in content_type or "mpeg" in content_type, f"Unexpected content type: {content_type}"
        
        print("\n✅ Stream test passed!")
        return True
        
    except requests.exceptions.HTTPError as e:
        print(f"❌ HTTP Error: {e}")
        print(f"Response: {response.text}")
        return False
    except Exception as e:
        print(f"❌ Error: {e}")
        return False


